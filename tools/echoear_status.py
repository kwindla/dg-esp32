#!/usr/bin/env python3
"""Derive standalone status fixtures; source assets/ remains read-only."""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw
from dgi import encode
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'assets/characters/halloween-cat'
OUT=ROOT/'hil/fixtures/echoear360'
# Fixed 5x7 glyphs: deterministic, no platform font dependency.
FONT={
'C':['01111','10000','10000','10000','10000','10000','01111'],
'D':['11110','10001','10001','10001','10001','10001','11110'],
'E':['11111','10000','10000','11110','10000','10000','11111'],
'G':['01111','10000','10000','10111','10001','10001','01111'],
'I':['111','010','010','010','010','010','111'],
'N':['10001','11001','11001','10101','10011','10011','10001'],
'O':['01110','10001','10001','10001','10001','10001','01110'],
'S':['01111','10000','10000','01110','00001','00001','11110'],
'T':['11111','00100','00100','00100','00100','00100','00100']}

def label(image,text,y):
    d=ImageDraw.Draw(image);scale=3
    width=sum(len(FONT[c][0])+1 for c in text)*scale-scale;x=(360-width)//2
    d.rounded_rectangle((x-8,y-6,x+width+7,y+26),radius=6,fill=(16,5,30,255))
    for c in text:
        for row,line in enumerate(FONT[c]):
            for col,bit in enumerate(line):
                if bit=='1':d.rectangle((x+col*scale,y+row*scale,x+col*scale+scale-1,y+row*scale+scale-1),fill=(255,247,217,255))
        x+=(len(FONT[c][0])+1)*scale

def face(eyes,title,dim):
    base=Image.open(SOURCE/'halloween-cat-faceplate-412.png').convert('RGBA')
    for sprite,x,y in [('mouth-closed',168,192),('eyes-'+eyes,152,176),('whiskers-rest',92,180)]:
        base.alpha_composite(Image.open(SOURCE/'sprites'/f'{sprite}.png').convert('RGBA'),(x,y))
    base=base.resize((360,360),Image.Resampling.LANCZOS)
    base=Image.blend(base,Image.new('RGBA',base.size,(16,5,30,255)),dim)
    label(base,title,253)
    return base

def fixtures():
    yield 'disconnected',face('closed','DISCONNECTED',.55),0,0
    yield 'connecting',face('half','CONNECTING',.25),0,0
    for active in range(3):
        patch=Image.new('RGBA',(72,18),(0,0,0,0));draw=ImageDraw.Draw(patch)
        for n in range(3):
            x=9+24*n;draw.ellipse((x-5,4,x+5,14),fill=(255,247,217,255) if n==active else (120,107,114,255))
        yield 'dots-'+str(active),patch,144,285

def main():
    rows=[]
    for slot,(name,im,x,y) in enumerate(fixtures()):
        data=encode(*im.size,list(im.getdata()),codec=2)
        digest=hashlib.sha256(data).hexdigest();(OUT/(digest+'.dgi')).write_bytes(data)
        rows.append(dict(slot=slot,name=name,hash=digest,bytes=len(data),width=im.width,height=im.height,x=x,y=y))
    manifest=dict(version=1,panel=[360,360],period_ms=350,assets=rows)
    (OUT/'status.json').write_text(json.dumps(manifest,indent=2)+'\n')
    header=['// Generated by tools/echoear_status.py; persist these content hashes.', '#pragma once', '#include <cstddef>', 'namespace dg_display {', 'struct DemoAsset {const char* hash; unsigned bytes,width,height; int x,y;};', 'inline constexpr DemoAsset demo_assets[]={']
    for r in rows:header.append('    {"%s",%d,%d,%d,%d,%d},'%(r['hash'],r['bytes'],r['width'],r['height'],r['x'],r['y']))
    header+=['};','inline constexpr unsigned DemoAssetCount=sizeof(demo_assets)/sizeof(demo_assets[0]);','}']
    (ROOT/'components/dg_display/include/dg_display/demo_assets.h').write_text('\n'.join(header)+'\n')
    print(json.dumps(manifest,indent=2))
if __name__=='__main__':main()
